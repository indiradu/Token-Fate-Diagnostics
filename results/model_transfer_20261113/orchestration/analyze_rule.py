"""Score (code sets, in the sandbox) and analyze stage R0 / C2 records. Usage: analyze_rule.py SET LOCK [SET LOCK ...] -> results_rule.md
Per setting: arms D, S32, K4, P4, R0 (derived rule), CTL (frozen learned controller): correct answers, net against dense and against K4 (paired, bootstrap over questions), speed against dense and against K4 (ratio of mean latency in the
same process), calls, dense and partial calls; the derived rule's hyperparameters; the criterion of stage C (within 4 correct answers of K4 and at least 5% faster than K4)."""
import json
import sys

import common as C
import numpy as np

CODE = {"he164": None, "kod_held": "kod_held400"}
out = ["# Stage R0 and C2 (generated by analyze_rule.py)\n"]
args = sys.argv[1:]
for ds, lock in zip(args[::2], args[1::2]):
    import os
    tag = os.environ.get("RULE_TAG", "")
    p = C.OUT / f"records/rule_{tag + '_' if tag else ''}{ds}_{lock}.jsonl"
    rows = [r for r in C.rows(p) if r.get("status") == "ok"]
    if ds in CODE:
        by_id = {e["example_id"]: e for e in (C.he164() if ds == "he164" else C.rows(C.OUT / "manifests/kod_held400.jsonl"))}
        cache = {}
        for r in rows:
            k = (r["example_id"], r["text"])
            if k not in cache:
                cache[k] = C.score_paper_generation(r["text"], by_id[r["example_id"]])
            c, st = cache[k]
            if st in ("sandbox_error", "sandbox_unavailable"):
                raise SystemExit(f"scoring infrastructure failure ({st})")
            r["correct"], r["scoring_status"] = bool(c), st
    by = {}
    for r in rows:
        by.setdefault(r["arm"], {})[r["example_id"]] = r
    arms = list(by)
    ids = sorted(set.intersection(*[set(v) for v in by.values()]))
    n = len(ids)
    rng = np.random.default_rng(23)
    idx = rng.integers(0, n, (4000, n))
    g = lambda a, k: np.array([by[a][i][k] for i in ids], float)
    Dn = f"D:{lock}"
    D, K = g(Dn, "latency_s").mean(), g("K4", "latency_s").mean()
    dc, kc = g(Dn, "correct"), g("K4", "correct")
    rule = next((r["rule"] for r in rows if r["arm"] == "R0"), {})
    out += [f"\n## {ds} {lock}: {n} questions. Derived rule: layer {rule.get('partial_layer_start')}, rows {rule.get('partial_join')}, every {rule.get('partial_every_k')} calls ({rule.get('refreshes_per_block')} per block)\n",
            "| arm | correct | net vs dense [CI] | net vs K4 [CI] | speed vs dense | speed vs K4 | calls | dense | partial | criterion |", "|---|---|---|---|---|---|---|---|---|---|"]
    for a in sorted(arms, key=lambda a: -D / g(a, "latency_s").mean()):
        L = g(a, "latency_s"); c = g(a, "correct")
        d, k = c - dc, c - kc
        bd, bk = d[idx].sum(1), k[idx].sum(1)
        crit = "met" if (k.sum() >= -4 and K / L.mean() >= 1.05) else ""
        out.append(f"| {a} | {int(c.sum())} | {int(d.sum()):+d} [{np.percentile(bd, 2.5):+.0f}, {np.percentile(bd, 97.5):+.0f}] | {int(k.sum()):+d} [{np.percentile(bk, 2.5):+.0f}, {np.percentile(bk, 97.5):+.0f}] | "
                   f"{D / L.mean():.2f}x | {K / L.mean():.2f}x | {g(a, 'nfe').mean():.1f} | {g(a, 'dense_calls').mean():.1f} | {g(a, 'partial_calls').mean():.1f} | {crit if a in ('R0', 'CTL', 'P4', 'S32') else ''} |")
(C.OUT / ("results_rule_" + os.environ.get("RULE_TAG", "") + ".md" if os.environ.get("RULE_TAG") else "results_rule.md")).write_text("\n".join(out) + "\n")
print("\n".join(out))
