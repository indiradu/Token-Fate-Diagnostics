"""CPU analysis of stage G (PREREGISTERED.md, section "Stage G"). Usage: analyze_agreement.py -> results_stageG.md
Unit: a cached call t (kind 'none') that is the j-th call after the last dense call, j >= 3. Label y = 1 if any word WRITTEN at call t differs from the dense pass's proposal at that row (committed disagreement).
Features come from calls before t only (plus the clock and the size of t's window):
 F0 clock: j, words written since the last dense call, progress of the block, rows in the window.
 F1 = F0 + free cached-call signals of call t-1: b = share of the still-blank rows common to calls t-1 and t-2 whose cached proposal did not change; mean and min proposal probability in the window; words written; mean probability of the written words.
 F2 = F1 + the refresh-type signal of call t-1: a = share of those common rows where the DENSE pass at t-1 proposes what the cached call t-2 proposed; and a - b.
Models fitted on kod_tune only; scored on he164 and gsm_tune. Bootstrap over questions (2,000 resamples, seed 23)."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

import os
OUT = Path(__file__).resolve().parents[1] / os.environ.get("MODEL_TAG", "llada15")
BLOCK = 32
F0 = ["j", "words_since_dense", "progress", "n_window"]
F1 = F0 + ["b", "mean_p", "min_p", "n_written_prev", "written_p_prev"]
F2 = F1 + ["a", "a_minus_b"]


def rows(ds):
    p = OUT / f"records/agree_{ds}.jsonl"
    return [json.loads(x) for x in p.read_text().splitlines() if x.strip()] if p.exists() else []


def build(ds):
    X, y, g = [], [], []
    for r in rows(ds):
        kinds, calls, wr = r["kinds"], r["calls"], r["written"]
        since_dense_idx, words_block, blk_prev = -1, 0, None
        for t, k in enumerate(kinds):
            blk = r["call_blocks"][t]
            if k in ("first", "dense"):
                since_dense_idx = t
            if blk != blk_prev:
                words_block, blk_prev = 0, blk
            j = t - since_dense_idx
            words_since = sum(len(wr[s]) for s in range(since_dense_idx, t))
            if k == "none" and j >= 3:
                c, c1, c2 = calls[t], calls[t - 1], calls[t - 2]
                cm = {p: (tk, pr) for p, tk, pr in zip(c["pos"], c["cached_tok"], c["dense_tok"])}
                dense_at = dict(zip(c["pos"], c["dense_tok"]))
                cached_at = dict(zip(c["pos"], c["cached_tok"]))
                lab = int(any(cached_at.get(p) is not None and cached_at[p] != dense_at[p] for p in wr[t]))
                c1c, c1d, c1p = dict(zip(c1["pos"], c1["cached_tok"])), dict(zip(c1["pos"], c1["dense_tok"])), c1["cached_p"]
                c2c = dict(zip(c2["pos"], c2["cached_tok"]))
                shared = [p for p in c1["pos"] if p in c2c]
                b = float(np.mean([c1c[p] == c2c[p] for p in shared])) if shared else 1.0
                a = float(np.mean([c1d[p] == c2c[p] for p in shared])) if shared else 1.0
                wp = [pp for p, pp in zip(c1["pos"], c1["cached_p"]) if p in set(wr[t - 1])]
                X.append([j, words_since, words_block / BLOCK, len(c["pos"]), b, float(np.mean(c1p)), float(np.min(c1p)), len(wr[t - 1]), float(np.mean(wp)) if wp else 0.0, a, a - b])
                y.append(lab)
                g.append(r["example_id"])
            words_block += len(wr[t])
    return np.array(X, float), np.array(y, int), np.array(g)


def fit(model, cols, Xtr, ytr):
    idx = [(F2).index(c) for c in cols]
    m = make_pipeline(StandardScaler(), LogisticRegression(max_iter=2000, C=1.0)) if model == "logit" else HistGradientBoostingClassifier(max_iter=150, max_depth=3, learning_rate=0.05, random_state=23)
    m.fit(Xtr[:, idx], ytr)
    return m, idx


def boot_auc(p_by, y, g, B=2000, seed=23):
    """AUROC of each prediction vector on all rows and the bootstrap (over question ids) of AUROC and paired differences."""
    ids = np.unique(g)
    by = {q: np.where(g == q)[0] for q in ids}
    rng = np.random.default_rng(seed)
    res = {k: [] for k in p_by}
    for _ in range(B):
        sel = np.concatenate([by[q] for q in rng.choice(ids, len(ids))])
        if len(set(y[sel])) < 2:
            continue
        for k, p in p_by.items():
            res[k].append(roc_auc_score(y[sel], p[sel]))
    return res


def main():
    Xtr, ytr, gtr = build("kod_tune")
    lines = ["# Stage G: does agreement of proposals track staleness? (generated by analyze_agreement.py)\n",
             f"Training set kod_tune: {len(ytr)} cached calls with j >= 3, {len(set(gtr))} questions, prevalence of committed disagreement {ytr.mean():.3f}.\n"]
    if len(ytr) == 0:
        raise SystemExit("no training rows")
    for model in ("logit", "hgb"):
        fitted = {n: fit(model, cols, Xtr, ytr) for n, cols in (("F0", F0), ("F1", F1), ("F2", F2))}
        for ds in ("he164", "gsm_tune"):
            X, y, g = build(ds)
            if len(y) == 0 or len(set(y)) < 2:
                lines.append(f"\n{model} on {ds}: no usable rows\n")
                continue
            pred = {n: m.predict_proba(X[:, idx])[:, 1] for n, (m, idx) in fitted.items()}
            bs = boot_auc(pred, y, g)
            auc = {n: roc_auc_score(y, p) for n, p in pred.items()}
            def d(a, b):
                n = min(len(bs[a]), len(bs[b]))
                diff = np.array(bs[a][:n]) - np.array(bs[b][:n])
                return f"{auc[a] - auc[b]:+.3f} [{np.percentile(diff, 2.5):+.3f}, {np.percentile(diff, 97.5):+.3f}]"
            lines += [f"\n## {model}, tested on {ds}: {len(y)} cached calls, {len(set(g))} questions, prevalence {y.mean():.3f}\n",
                      "| feature set | AUROC [95% CI over questions] |", "|---|---|"]
            lines += [f"| {n} | {auc[n]:.3f} [{np.percentile(bs[n], 2.5):.3f}, {np.percentile(bs[n], 97.5):.3f}] |" for n in ("F0", "F1", "F2")]
            lines += [f"\nF1 - F0: {d('F1', 'F0')}   F2 - F1: {d('F2', 'F1')}   F2 - F0: {d('F2', 'F0')}"]
    (OUT / "results_stageG.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
