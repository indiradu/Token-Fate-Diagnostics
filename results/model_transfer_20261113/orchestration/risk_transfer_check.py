"""Stage G3 (PREREGISTERED.md): does the cache controller's risk model (fitted on LLaDA-8B-Instruct, frozen) transfer to another model? CPU only, on the stage-G-style records of the new model
(plain S32 decodes with a shadow dense pass): records/agree_<set>.jsonl under MODEL_TAG. Usage: MODEL_TAG=llada15 risk_transfer_check.py -> <MODEL_TAG>/results_risk_transfer.md
(A) the frozen LLaDA-8B risk model on the new model's calls: AUROC per set; (B) a risk model fitted on the NEW model's kod_tune records: AUROC on its he164 and gsm_tune (the in-model reference); (C) clock only;
(D) threshold transfer: the frozen model with the LLaDA-8B training thresholds (top shares 0.3, 0.1, 0.03): fire share of the new model's calls against nominal and the disagreement lift; (E) re-calibration of those thresholds from the first 10 and 20 prompts."""
from __future__ import annotations

import json
import os
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.preprocessing import StandardScaler

import analyze_agreement as A

TAG = os.environ.get("MODEL_TAG", "llada15")
OUT = Path(__file__).resolve().parents[1] / TAG
FROZEN = json.loads((Path(__file__).resolve().parents[2] / "refresh_family_20261111/records/risk_model_F1.json").read_text())
SHARES = (0.3, 0.1, 0.03)
IDX1, IDX0 = [A.F2.index(c) for c in A.F1], [A.F2.index(c) for c in A.F0]


def frozen(Z):
    z = (Z - np.array(FROZEN["mean"])) / np.array(FROZEN["scale"])
    return 1.0 / (1.0 + np.exp(-(z @ np.array(FROZEN["coef"]) + FROZEN["intercept"])))


def fit(X, y):
    sc = StandardScaler().fit(X); m = LogisticRegression(max_iter=3000).fit(sc.transform(X), y)
    return lambda Z: m.predict_proba(sc.transform(Z))[:, 1]


def boot(p, y, g, B=500):
    ids = np.unique(g); by = {q: np.where(g == q)[0] for q in ids}; rng = np.random.default_rng(23); o = []
    for _ in range(B):
        s = np.concatenate([by[q] for q in rng.choice(ids, len(ids))])
        if len(set(y[s])) > 1:
            o.append(roc_auc_score(y[s], p[s]))
    return np.percentile(o, [2.5, 97.5])


def main():
    D = {d: A.build(d) for d in ("kod_tune", "he164", "gsm_tune") if (OUT / f"records/agree_{d}.jsonl").exists()}
    L = [f"# Stage G3: risk-model transfer to {TAG} (generated by risk_transfer_check.py)\n", "Calls (j >= 3), questions, disagreement rate: " + "; ".join(f"{d}: {len(D[d][1])}, {len(set(D[d][2]))}, {D[d][1].mean():.3f}" for d in D) + "\n",
         "| set | (A) frozen LLaDA-8B risk model | (B) fitted on this model's kod_tune | (C) clock only (fitted on this model's kod_tune) |", "|---|---|---|---|"]
    ref = fit(D["kod_tune"][0][:, IDX1], D["kod_tune"][1]) if "kod_tune" in D else None
    ref0 = fit(D["kod_tune"][0][:, IDX0], D["kod_tune"][1]) if "kod_tune" in D else None
    for d, (X, y, g) in D.items():
        pa = frozen(X[:, IDX1]); lo, hi = boot(pa, y, g)
        cell_b = "(in-sample)" if d == "kod_tune" else f"{roc_auc_score(y, ref(X[:, IDX1])):.3f}"
        cell_c = "(in-sample)" if d == "kod_tune" else f"{roc_auc_score(y, ref0(X[:, IDX0])):.3f}"
        L.append(f"| {d} | {roc_auc_score(y, pa):.3f} [{lo:.3f}, {hi:.3f}] | {cell_b} | {cell_c} |")
    L += ["\n## Threshold transfer (frozen LLaDA-8B model and thresholds)\n", "| set | top share (nominal) | share above the LLaDA-8B threshold | lift |", "|---|---|---|---|"]
    for d, (X, y, g) in D.items():
        p = frozen(X[:, IDX1])
        for q in SHARES:
            f = p >= FROZEN["top_share_thresholds"][str(q)]
            L.append(f"| {d} | {q} | {f.mean():.3f} ({f.mean() / q - 1:+.0%}) | {(y[f].mean() / y.mean() if f.any() else float('nan')):.2f}x |")
    L += ["\n## Re-calibration from the first n prompts of this model/set (fire share on the rest, mean of 50 orders)\n", "| set | n | 0.3 | 0.1 | 0.03 |", "|---|---|---|---|---|"]
    for d, (X, y, g) in D.items():
        p = frozen(X[:, IDX1]); ids = np.unique(g)
        for n in (10, 20):
            r = {q: [] for q in SHARES}; rng = np.random.default_rng(23)
            for _ in range(50):
                o = rng.permutation(ids); cal = np.isin(g, o[:n])
                for q in SHARES:
                    r[q].append((p[~cal] >= np.quantile(p[cal], 1 - q)).mean())
            L.append(f"| {d} | {n} | " + " | ".join(f"{np.mean(r[q]):.3f}" for q in SHARES) + " |")
    (OUT / "results_risk_transfer.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
